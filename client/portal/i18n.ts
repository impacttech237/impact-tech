export type Key = keyof typeof fr;
const DICTS = { fr, en };
let current: "fr" | "en" = "fr";

export function setLocale(l: string) {
  current = l === "en" ? "en" : "fr";
  document.documentElement.lang = current;
}
export const getLocale = () => current;

export function t(key: Key, vars: Record<string, any> = {}): string {
  const s = (DICTS[current] as any)[key] ?? (fr as any)[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_: string, k: string) => (vars[k] ?? "").toString());
}

export function hasKey(key: string): key is Key {
  return key in fr;
}

/* Dates lisibles : « 12 octobre », « il y a 3 h » */
export function fmtDate(iso?: string | null, withYear = false) {
  if (!iso) return "";
  const d = new Date(iso.length === 10 ? `${iso}T12:00:00Z` : iso.includes("T") ? iso : iso.replace(" ", "T") + "Z");
  return d.toLocaleDateString(current === "en" ? "en-GB" : "fr-FR", { day: "numeric", month: "long", ...(withYear ? { year: "numeric" } : {}) });
}

export function fmtRelative(iso?: string | null) {
  if (!iso) return "";
  const d = new Date(iso.includes("T") ? iso : iso.replace(" ", "T") + "Z");
  const diff = (Date.now() - d.getTime()) / 1000;
  const rtf = new Intl.RelativeTimeFormat(current === "en" ? "en" : "fr", { numeric: "auto" });
  if (diff < 60) return rtf.format(0, "second");
  if (diff < 3600) return rtf.format(-Math.round(diff / 60), "minute");
  if (diff < 86400) return rtf.format(-Math.round(diff / 3600), "hour");
  if (diff < 86400 * 7) return rtf.format(-Math.round(diff / 86400), "day");
  return fmtDate(iso);
}

export function fmtMoney(amount?: number | null, currency = "XAF") {
  if (amount == null) return "";
  const n = Math.round(amount).toString().replace(/\B(?=(\d{3})+(?!\d))/g, current === "en" ? "," : " ");
  return currency === "EUR" ? (current === "en" ? `€${n}` : `${n} €`) : `${n} FCFA`;
}

export function fmtSize(bytes?: number | null) {
  if (!bytes) return "";
  const u = ["o", "Ko", "Mo", "Go"];
  const uEn = ["B", "KB", "MB", "GB"];
  let i = 0;
  let v = bytes;
  while (v >= 1024 && i < 3) {
    v /= 1024;
    i++;
  }
  return `${v < 10 && i ? v.toFixed(1) : Math.round(v)} ${(current === "en" ? uEn : u)[i]}`;
}
